export type Translations = (typeof translations)[Locale]

export function getTranslations(locale: Locale = defaultLocale) {
  return translations[locale]
}

export function translateArticleLabel(value: string, locale: Locale = defaultLocale) {
  const taxonomy = translations[locale].taxonomy.article as Record<string, string>
  return taxonomy[value] ?? value
}

export function translateResourceLabel(value: string, locale: Locale = defaultLocale) {
  const taxonomy = translations[locale].taxonomy.resource as Record<string, string>
  return taxonomy[value] ?? value
}
